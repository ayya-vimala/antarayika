#!/usr/bin/env python3
"""Convert the 'newtable' sheet of an .ods file into a LaTeX longtable.

Usage:
    pip install pandas odfpy
    python3 ods2tex.py Roloff_Table2_Antarayika_Dharmas.ods [newtable] > table.tex

In your document (preamble needs longtable, booktabs, array, pdflscape):
    \\input{table.tex}
"""
import re
import sys

import pandas as pd

HEADER_ROWS = 3  # rows 0-2: school names, sources, languages
# Column widths (cm) for the 10 columns; they sum to about 23 cm (plus column padding), which fits
# landscape A4 with your current margins at \scriptsize.
WIDTHS = [3.0, 2.0, 1.9, 1.9, 1.8, 2.0, 2.3, 2.0, 3.1, 2.9]
# Grouped headers in row 0: (first column, last column), counting from 0.
GROUPS = {5: (5, 6), 7: (7, 9)}

SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def tex(value):
    """Escape a cell value; empty cells become ''."""
    if pd.isna(value):
        return ""
    s = re.sub(r"\s+", " ", str(value)).strip()  # collapse stray whitespace
    s = "".join(SPECIAL.get(ch, ch) for ch in s)
    return s.replace(" + ", r" \newline + ")  # joined entries on separate lines


def header_block(df):
    ncol = df.shape[1]
    names = [tex(v) for v in df.iloc[0]]
    row0, rules, c = [], [], 0
    while c < ncol:
        if c in GROUPS:
            a, b = GROUPS[c]
            spec = "c" + ("G" if b < ncol - 1 else "")
            row0.append(rf"\multicolumn{{{b - a + 1}}}{{{spec}}}{{\scriptsize {names[a]}}}")
            rules.append(rf"\cmidrule(lr){{{a + 1}-{b + 1}}}")
            c = b + 1
        else:
            spec = rf"P{{{WIDTHS[c]}cm}}" + ("G" if c < ncol - 1 else "")
            row0.append(rf"\multicolumn{{1}}{{{spec}}}{{{names[c]}}}" if names[c] else "")
            if names[c]:
                rules.append(rf"\cmidrule(lr){{{c + 1}-{c + 1}}}")
            c += 1
    lines = [" & ".join(row0) + r" \\", "".join(rules)]
    for r in (1, 2):
        lines.append(" & ".join(tex(v) for v in df.iloc[r]) + r" \\")
    lines.append(r"\midrule")
    return lines


def main():
    path = sys.argv[1]
    sheet = sys.argv[2] if len(sys.argv) > 2 else "newtable"
    df = pd.read_excel(path, sheet_name=sheet, header=None, engine="odf")
    ncol = df.shape[1]
    colspec = "G".join(rf"P{{{w}cm}}" for w in WIDTHS[:ncol])
    head = header_block(df)

    out = [
        r"% Generated by ods2tex.py; edit the .ods and re-run rather than editing this file.",
        r"\begin{landscape}",
        r"\newcolumntype{P}[1]{>{\raggedright\arraybackslash\scriptsize}p{#1}}",
        r"% needs \usepackage{colortbl} (and xcolor) in the preamble",
        r"\newcolumntype{G}{!{\color{black!25}\vrule width 0.3pt}}",
        r"\providecommand{\grayrule}{\arrayrulecolor{black!25}\hline\arrayrulecolor{black}}",
        r"\setlength{\tabcolsep}{1.5pt}",
        r"\renewcommand{\arraystretch}{1.15}",
        rf"\begin{{longtable}}{{{colspec}}}",
        r"\caption{Antarāyika dharmas}\label{tab:roloff}\\",
        r"\toprule",
        *head,
        r"\endfirsthead",
        r"\toprule",
        *head,
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]

    rows = []  # (is_section, text)
    for r in range(HEADER_ROWS, len(df)):
        row = df.iloc[r]
        if row.isna().all():
            continue
        if pd.notna(row.iloc[0]) and row.iloc[1:].isna().all():  # section row
            rows.append((True, tex(row.iloc[0])))
        else:
            rows.append((False, " & ".join(tex(v) for v in row)))

    for i, (is_sec, text) in enumerate(rows):
        prev_sec = i > 0 and rows[i - 1][0]
        nxt_sec = i + 1 < len(rows) and rows[i + 1][0]
        if is_sec:
            # \\* forbids a page break after the row, so a section title is never
            # left alone at the bottom of a page
            out.append(rf"\midrule\multicolumn{{{ncol}}}{{l}}{{\textit{{{text}}}}} \\*")
        else:
            # first row after a section title also gets \\*, so at least two rows follow it
            end = r" \\*" if prev_sec else r" \\"
            rule = "" if (nxt_sec or i == len(rows) - 1) else r" \grayrule"
            out.append(text + end + rule)

    out += [r"\end{longtable}", r"\end{landscape}", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
